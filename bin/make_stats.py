#!/usr/bin/env python3
"""Regenerate _data/publication_stats.yml (used by the "Research at a glance" block on the About page).

Usage:  python3 bin/make_stats.py
Run it after editing _bibliography/papers.bib. Needs no internet.
Papers are counted per year as journal, conference or other (chapters, editorials, edited books).
Themes come from the `themes = {a, b}` field of each entry (ids are defined in _data/research_themes.yml).
Entries without `themes` are listed at the end so you can tag them.
"""
import os, re
from collections import Counter

ROOT = os.path.join(os.path.dirname(__file__), "..")
BIB = os.path.join(ROOT, "_bibliography", "papers.bib")
OUT = os.path.join(ROOT, "_data", "publication_stats.yml")
KIND = {"journal": "journal", "conference": "conference", "chapter": "other", "editorial": "other", "edited": "other"}

text = open(BIB, encoding="utf-8").read()
years, themes, untagged, total = {}, Counter(), [], 0
for part in re.split(r"(?m)^(?=@\w+\{)", text):
    sec = re.search(r"section\s*=\s*\{(\w+)\}", part)
    if not sec or sec.group(1) not in KIND:
        continue
    year = re.search(r"year\s*=\s*\{(\d{4})\}", part)
    key = re.match(r"@\w+\{([^,]+),", part).group(1)
    if not year:
        continue
    total += 1
    y = int(year.group(1))
    years.setdefault(y, Counter())[KIND[sec.group(1)]] += 1
    th = re.search(r"themes\s*=\s*\{([^}]*)\}", part)
    if th:
        for t in [x.strip() for x in th.group(1).split(",") if x.strip()]:
            themes[t] += 1
    else:
        untagged.append(key)

lines = [f"total: {total}", "years:"]
for y in range(min(years), max(years) + 1):
    c = years.get(y, Counter())
    lines += [f"  - year: {y}", f"    journal: {c['journal']}", f"    conference: {c['conference']}", f"    other: {c['other']}"]
lines.append("themes:")
for t, n in sorted(themes.items()):
    lines += [f"  - id: {t}", f"    count: {n}"]
header = "# Generated by bin/make_stats.py from _bibliography/papers.bib. Do not edit by hand.\n"
open(OUT, "w", encoding="utf-8").write(header + "\n".join(lines) + "\n")
print(f"{total} papers, {len(years)} years, {len(themes)} themes written to _data/publication_stats.yml")
if untagged:
    print("Without a themes field:", ", ".join(untagged))
